export function getCountryByCode(code: string, overrides?: Country[]): Country {
  const fromOverrides = overrides?.find((c) => c.code === code);
  if (fromOverrides) return fromOverrides;
  const fromWorld = WORLD_COUNTRIES.find((c) => c.code === code);
  if (fromWorld) return fromWorld;
  return WORLD_COUNTRIES[0];
}
